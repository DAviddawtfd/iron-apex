export type Location = 'home' | 'gym';
export type Equipment = 'home' | 'gym' | 'band';
export type ExerciseKind = 'compound' | 'isolation' | 'core';
export type WorkoutId =
  | 'home-push'
  | 'home-pull'
  | 'home-legs'
  | 'home-upper'
  | 'gym-push'
  | 'gym-pull'
  | 'gym-legs'
  | 'gym-upper'
  | 'band-upper';

export interface Exercise {
  id: string;
  name: string;
  sets: number;
  reps: string;
  rest: number;
  kind: ExerciseKind;
  /** Приоритет набора: верх груди, руки, средние дельты (+1 подход на «Наборе») */
  priority?: boolean;
  tempo?: string;
  superset?: boolean;
  note?: string;
  /** Замены строго внутри инвентаря этой программы */
  alts: string[];
}

export interface Workout {
  id: WorkoutId;
  title: string;
  short: string;
  equipment: Equipment;
  focus: string;
  exercises: Exercise[];
}

